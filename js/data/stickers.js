export function getBook(id) {
  return STICKER_BOOKS.find((b) => b.id === id) || null;
}

const BY_ID = new Map(STICKER_BOOKS.flatMap((book) => book.stickers.map((st) => [st.id, { ...st, book: book.id }])));

/** Gommette (avec l'identifiant de son album), ou null si inconnue. */
export function findSticker(id) {
  return BY_ID.get(id) || null;
}
